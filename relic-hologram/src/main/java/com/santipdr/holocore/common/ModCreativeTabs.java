package com.santipdr.holocore.common;

import com.santipdr.holocore.HoloCore;
import net.minecraft.core.registries.Registries;
import net.minecraft.network.chat.Component;
import net.minecraft.world.item.CreativeModeTab;
import net.minecraft.world.item.ItemStack;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.registries.DeferredRegister;
import net.minecraftforge.registries.RegistryObject;

/** Pestana creativa propia para que la reliquia se encuentre de un vistazo. */
public final class ModCreativeTabs {

    public static final DeferredRegister<CreativeModeTab> TABS =
            DeferredRegister.create(Registries.CREATIVE_MODE_TAB, HoloCore.MOD_ID);

    public static final RegistryObject<CreativeModeTab> MAIN = TABS.register("main",
            () -> CreativeModeTab.builder()
                    .title(Component.translatable("itemGroup." + HoloCore.MOD_ID))
                    .icon(() -> new ItemStack(ModItems.HOLOGRAPHIC_CORE.get()))
                    .displayItems((params, output) -> output.accept(ModItems.HOLOGRAPHIC_CORE.get()))
                    .build());

    private ModCreativeTabs() {
    }

    public static void register(IEventBus modBus) {
        TABS.register(modBus);
    }
}
